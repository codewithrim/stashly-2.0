import 'package:supabase_flutter/supabase_flutter.dart' hide AuthException;
import '../../core/errors.dart';

class ShareLinkInfo {
  final String token;
  final String itemId;
  final DateTime createdAt;
  final DateTime? revokedAt;

  const ShareLinkInfo({
    required this.token,
    required this.itemId,
    required this.createdAt,
    this.revokedAt,
  });

  bool get isActive => revokedAt == null;
}

class ShareLinkService {
  final SupabaseClient _supabase;

  ShareLinkService(this._supabase);

  /// Fetch active share link for the item if one exists
  Future<ShareLinkInfo?> getActiveLinkForItem(String itemId) async {
    try {
      final rows = await _supabase
          .from('share_links')
          .select()
          .eq('item_id', itemId)
          .isFilter('revoked_at', null)
          .limit(1);

      if (rows.isEmpty) return null;
      final data = rows.first;
      return ShareLinkInfo(
        token: data['token'] as String,
        itemId: data['item_id'] as String,
        createdAt: DateTime.parse(data['created_at'] as String),
        revokedAt: data['revoked_at'] != null ? DateTime.parse(data['revoked_at'] as String) : null,
      );
    } catch (_) {
      return null;
    }
  }

  /// Create a new public unguessable share link (48 hex chars generated by postgres default)
  Future<ShareLinkInfo> createShareLink(String itemId) async {
    final user = _supabase.auth.currentUser;
    if (user == null) {
      throw const AuthException('Must be signed in to create public links.');
    }

    try {
      final rows = await _supabase.from('share_links').insert({
        'item_id': itemId,
        'owner_id': user.id,
      }).select();

      final data = rows.first;
      return ShareLinkInfo(
        token: data['token'] as String,
        itemId: data['item_id'] as String,
        createdAt: DateTime.parse(data['created_at'] as String),
      );
    } catch (e) {
      throw UnknownException('Could not create public link: $e');
    }
  }

  /// Revoke the link by setting revoked_at timestamp
  Future<void> revokeShareLink(String token) async {
    try {
      await _supabase.from('share_links').update({
        'revoked_at': DateTime.now().toUtc().toIso8601String(),
      }).eq('token', token);
    } catch (e) {
      throw UnknownException('Could not revoke link: $e');
    }
  }
}
